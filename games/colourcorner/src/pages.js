const E = (s, x, y, rx, ry = rx) => ({ k: "e", v: [x, y, rx, ry], s });
const P = (s, points) => ({ k: "p", v: points.flat(), s });
const R = (s, commands) => ({ k: "d", v: commands, s });
const Q = (s, x, y, w, h, r = 8) => ({ k: "r", v: [x, y, w, h, r], s });

function petal(s, cx, cy, length, width, angle) {
  const c = Math.cos(angle);
  const n = Math.sin(angle);
  const at = (x, y) => [cx + x * c - y * n, cy + x * n + y * c];
  return R(s, [["M", ...at(0, 0)], ["Q", ...at(length * 0.45, -width), ...at(length, 0)], ["Q", ...at(length * 0.45, width), ...at(0, 0)], ["Z"]]);
}

function flowerShape(x, y, s) {
  const commands = [];
  for (let at = 0; at < 6; at += 1) {
    const a = (at * Math.PI) / 3;
    const tip = (turn, reach) => [x + Math.cos(a + turn) * reach, y + Math.sin(a + turn) * reach];
    commands.push(["M", x, y], ["Q", ...tip(-0.4, 25), ...tip(0, 25)], ["Q", ...tip(0.4, 25), x, y], ["Z"]);
  }
  return R(s, commands);
}

function starShape(x, y, radius, s) {
  return P(s, Array.from({ length: 10 }, (_, at) => {
    const a = -Math.PI / 2 + (at * Math.PI) / 5;
    const r = at % 2 ? radius * 0.45 : radius;
    return [x + Math.cos(a) * r, y + Math.sin(a) * r];
  }));
}

