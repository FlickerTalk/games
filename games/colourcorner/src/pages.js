function mandala() {
  const regions = [];
  for (let at = 0; at < 8; at += 1) {
    const a = (at * Math.PI) / 4;
    const b = a + Math.PI / 4;
    const half = (a + b) / 2;
    const at2 = (angle, reach) => [150 + Math.cos(angle) * reach, 180 + Math.sin(angle) * reach];
    regions.push(R(at % 2 ? C.coral : C.yellow, [["M", ...at2(a, 124)], ["L", ...at2(a, 147)], ["Q", ...at2(half, 159), ...at2(b, 147)], ["L", ...at2(b, 124)], ["Q", ...at2(half, 132), ...at2(a, 124)], ["Z"]]));
  }
  for (let at = 0; at < 8; at += 1) regions.push(petal(at % 2 ? C.cyan : C.blue, 150, 180, 114, 25, (at * Math.PI) / 4 + Math.PI / 8));
  for (let at = 0; at < 6; at += 1) regions.push(petal(at % 2 ? C.pink : C.purple, 150, 180, 62, 20, (at * Math.PI) / 3));
  regions.push(E(C.yellow, 150, 180, 22));
  return regions;
}

